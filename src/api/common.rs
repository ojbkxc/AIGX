/// 判断 IPv4 是否属于中国大陆主干段。
///
/// 表第一列为 CIDR（`a.b.c.d/prefix`），按掩码位运算匹配。
fn ipv4_in_mainland(ip: &str) -> bool {
    let Some(n) = parse_ipv4_u32(ip) else {
        return false;
    };
    CHINA_MAINLAND_IPV4_CIDRS.iter().any(|(cidr, _)| {
        let Some((addr, prefix)) = parse_cidr_u32(cidr) else {
            return false;
        };
        let mask: u32 = if prefix >= 32 {
            u32::MAX
        } else {
            u32::MAX << (32 - prefix)
        };
        (n & mask) == (addr & mask)
    })
}

/// 解析 `a.b.c.d/prefix` 为 (网络地址, 前缀长度)。
fn parse_cidr_u32(s: &str) -> Option<(u32, u8)> {
    let (addr_str, prefix_str) = s.split_once('/')?;
    let addr = parse_ipv4_u32(addr_str)?;
    let prefix: u8 = prefix_str.parse().ok()?;
    if prefix > 32 {
        return None;
    }
    Some((addr, prefix))
}

/// 解析点分 IPv4 为 u32。
fn parse_ipv4_u32(s: &str) -> Option<u32> {
    let mut parts = [0u8; 4];
    let mut it = s.split('.');
    for slot in parts.iter_mut() {
        let p = it.next()?;
        let v: u32 = p.parse().ok()?;
        if v > 255 {
            return None;
        }
        *slot = v as u8;
    }
    if it.next().is_some() {
        return None;
    }
    Some(u32::from_be_bytes(parts))
}

