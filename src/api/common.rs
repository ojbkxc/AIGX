/// - 其他（含无法识别/IPv6/私有 IP）→ `en`
///
/// 仅用于登录页默认语言，不涉及权限判断；识别不到时由前端
/// 回退到浏览器 `navigator.language`。
pub fn geo_language_for_ip(ip: &str) -> Option<&'static str> {
    if ip.contains(':') {
        // IPv6：无内置段表，不猜测（前端走 navigator.language）
        return None;
    }
    if ipv4_in_mainland(ip) {
        Some("zh")
    } else {
        Some("en")
    }
}

#[cfg(test)]
mod geo_tests {
    use super::*;

    #[test]
    fn mainland_ipv4_is_zh() {
        // 联通/电信/移动主干段样本
        assert_eq!(geo_language_for_ip("114.114.114.114"), Some("zh")); // 江苏 DNS
        assert_eq!(geo_language_for_ip("223.5.5.5"), Some("zh")); // 杭州 DNS
        assert_eq!(geo_language_for_ip("39.156.66.10"), Some("zh")); // 移动
        assert_eq!(geo_language_for_ip("202.96.209.133"), Some("zh")); // 上海电信
        assert_eq!(geo_language_for_ip("1.24.8.8"), Some("zh")); // 1.24.0.0/13 段内
    }

    #[test]
    fn foreign_ipv4_is_en() {
        assert_eq!(geo_language_for_ip("8.8.8.8"), Some("en")); // Google
        assert_eq!(geo_language_for_ip("1.1.1.1"), Some("en")); // Cloudflare
        assert_eq!(geo_language_for_ip("203.0.113.1"), Some("en")); // TEST-NET
    }

    #[test]
    fn ipv6_returns_none() {
        assert_eq!(geo_language_for_ip("2001:db8::1"), None);
        assert_eq!(geo_language_for_ip("::1"), None);
    }

    #[test]
    fn invalid_ip_falls_to_en() {
        assert_eq!(geo_language_for_ip("not-an-ip"), Some("en"));
        assert_eq!(geo_language_for_ip(""), Some("en"));
    }
}
